export const COLABORADORES_DEMARCHI: readonly Colaborador[] = RAW.split("\n").map((line) => {
  const [matricula, nome, especialidade] = line.split("|");
  return {
    matricula: matricula.trim(),
    nome: nome.trim(),
    unidade: "DEMARCHI",
    especialidade: especialidade.trim() as Especialidade,
  };
});

const BY_MATRICULA = new Map(COLABORADORES_DEMARCHI.map((c) => [c.matricula, c]));

export function findColaborador(matricula: string): Colaborador | undefined {
  return BY_MATRICULA.get(matricula.trim());
}

export function colaboradoresPorEspecialidade(esp: Especialidade): Colaborador[] {
  return COLABORADORES_DEMARCHI.filter((c) => c.especialidade === esp).sort((a, b) =>
    a.nome.localeCompare(b.nome, "pt-BR"),
  );
}
